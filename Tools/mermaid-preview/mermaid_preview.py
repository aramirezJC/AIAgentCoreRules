#!/usr/bin/env python3
"""Render local .mmd Mermaid sources into a single offline-viewable HTML page.

Usage:
    python3 mermaid_preview.py <file1.mmd> [file2.mmd ...] [--output PATH] [--open]

Purpose: let an architecture diagram be iterated on and sanity-checked locally
(syntax, relationships, rough layout) before it is ever pushed to a shared board
(Miro). The only network call the generated page makes is loading mermaid.js from
a CDN in the browser; this script itself never talks to Miro, Confluence, or any
AI model, and the render happens entirely in the browser, with no round trip of any
kind back through this script. See AIAgentCoreRules/Processes/ExternalDocPass.md,
"Diagrams reviewed on a board", for when to actually push to Miro instead.
"""
import argparse
import html
import json
import pathlib
import subprocess
import sys
import webbrowser

MERMAID_CDN = "https://cdnjs.cloudflare.com/ajax/libs/mermaid/10.9.1/mermaid.min.js"

PAGE_TEMPLATE = """<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>Mermaid preview</title>
<script src="{cdn}"></script>
<style>
  :root {{ color-scheme: light dark; }}
  body {{ font-family: -apple-system, system-ui, sans-serif; margin: 0; background: #fafafa; }}
  header {{ padding: 12px 16px; background: #1f2430; color: #eee; font-size: 14px; }}
  .tabs {{ display: flex; gap: 4px; padding: 8px 16px 0; background: #1f2430; }}
  .tab {{ background: #30384a; color: #ccc; border: none; padding: 8px 14px; border-radius: 6px 6px 0 0;
          cursor: pointer; font-size: 13px; }}
  .tab.active {{ background: #fafafa; color: #111; font-weight: 600; }}
  .panel {{ display: none; padding: 24px; overflow: auto; }}
  .panel.active {{ display: block; }}
  .diagram {{ background: white; padding: 16px; border-radius: 8px; box-shadow: 0 1px 4px rgba(0,0,0,.1); }}
  .error {{ color: #b00020; font-family: monospace; white-space: pre-wrap; }}
</style>
</head>
<body>
<header>Local Mermaid preview — generated by mermaid_preview.py, not published anywhere</header>
<div class="tabs">
{tab_buttons}
</div>
{panels}
<script>
  mermaid.initialize({{ startOnLoad: false, theme: "default" }});
  const sources = {{
{sources_js}
  }};
  async function renderAll() {{
    for (const [id, src] of Object.entries(sources)) {{
      const target = document.getElementById(id);
      try {{
        const {{ svg }} = await mermaid.render(id + "-svg", src);
        target.innerHTML = svg;
      }} catch (err) {{
        target.innerHTML = '<div class="error">' + (err && err.message ? err.message : err) + '</div>';
      }}
    }}
  }}
  function activate(idx) {{
    document.querySelectorAll(".tab").forEach((el, i) => el.classList.toggle("active", i === idx));
    document.querySelectorAll(".panel").forEach((el, i) => el.classList.toggle("active", i === idx));
  }}
  document.querySelectorAll(".tab").forEach((el, i) => el.addEventListener("click", () => activate(i)));
  activate(0);
  renderAll();
</script>
</body>
</html>
"""


def build_html(diagrams):
    tab_buttons = "\n".join(
        f'<button class="tab{" active" if i == 0 else ""}" data-i="{i}">{html.escape(title)}</button>'
        for i, (title, _src) in enumerate(diagrams)
    )
    panels = "\n".join(
        f'<div class="panel{" active" if i == 0 else ""}"><div class="diagram" id="d{i}"></div></div>'
        for i, (_title, _src) in enumerate(diagrams)
    )
    sources_js = ",\n".join(f'    "d{i}": {json.dumps(src)}' for i, (_title, src) in enumerate(diagrams))
    return PAGE_TEMPLATE.format(cdn=MERMAID_CDN, tab_buttons=tab_buttons, panels=panels, sources_js=sources_js)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="+", help="One or more .mmd files to render as tabs")
    parser.add_argument("--output", help="Output .html path (default: alongside the first input file)")
    parser.add_argument("--open", action="store_true", help="Open the result in the default browser")
    args = parser.parse_args()

    diagrams = []
    for f in args.files:
        path = pathlib.Path(f)
        diagrams.append((path.stem, path.read_text()))

    out_path = pathlib.Path(args.output) if args.output else pathlib.Path(args.files[0]).parent / "_mermaid_preview.html"
    out_path.write_text(build_html(diagrams))
    print(str(out_path))

    if args.open:
        if sys.platform == "darwin":
            subprocess.run(["open", str(out_path)], check=False)
        else:
            webbrowser.open(out_path.resolve().as_uri())


if __name__ == "__main__":
    main()
