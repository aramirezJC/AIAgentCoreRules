#!/usr/bin/env python3
"""
Mechanical lint for the coding-standards tags a regex or the declaration parser can decide.

Checks only the changed lines of each file (git diff against HEAD; an untracked file or a file
outside git counts as all lines), so a legacy file's old code does not drown the new code.

  [EXPLICIT] var                         [DI]    ServiceLocator.Instance
  [ALLMAN]   { at the end of a code line  [LOG]   UnityEngine Debug.Log*
  [ACCESS]   type or member with no access modifier
  [FIELD]    public field (const is allowed)
  [ASYNC]    async void that is not an override, an (object sender, …) handler or an On* handler

The judgement tags ([SRP] [IFACE] [RES] [SYM], method design, host rules) are /audit's.
Heuristics, deliberately quiet: initialisers (`new X {`, `= {`, `=> {`) are not [ALLMAN];
interface and enum members, static constructors, partial methods and explicit interface
implementations are not [ACCESS]; async void overrides are /audit's to judge (try/catch).

Usage
  cslint.py                       # changed .cs files of the repo at the cwd (vs HEAD, plus untracked)
  cslint.py path/A.cs path/B.cs   # those files, changed lines only
  cslint.py --all-lines path.cs   # every line
  cslint.py --base develop        # changed lines vs another ref

Prints `path:line: [TAG] message` per violation. Exit code 1 when there are violations.
Also run by the session-lifecycle PostToolUse Edit|Write hook (hook-lint) on each edited file.
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _csparse import SourceParser, blank_literals  # noqa: E402

VAR_RE = re.compile(r"(?<![\w.@])var\s+(?:[A-Za-z_]\w*|\()")
DEBUG_LOG_RE = re.compile(r"(?<![\w.])(?:UnityEngine\s*\.\s*)?Debug\s*\.\s*Log\w*\s*\(")
SERVICE_LOCATOR_RE = re.compile(r"\bServiceLocator\s*\.\s*Instance\b")
# A trailing `{` that opens an initialiser or a lambda body, not a block: allowed on the line.
INITIALISER_RE = re.compile(r"(?:=>|=|\bnew\b[^;{]*|\breturn\b|[(,])\s*\{$")
HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")
EVENT_HANDLER_RE = re.compile(r"\(\s*object\s+\w+\s*,|EventArgs\s+\w+\s*\)")
HANDLER_NAME_RE = re.compile(r"On[A-Z]")   # the project's listener / handler naming
GENERATED_MARKERS = ("<auto-generated", "<autogenerated")


def git(cwd, *args):
    result = subprocess.run(["git", "-C", cwd] + list(args), capture_output=True, text=True)
    return result.returncode, result.stdout


def changed_lines(path, base="HEAD"):
    """Set of 1-based line numbers changed vs base, or None for 'every line' (untracked / no git)."""
    folder = os.path.dirname(os.path.abspath(path)) or "."
    code, _ = git(folder, "ls-files", "--error-unmatch", "--", os.path.abspath(path))
    if code != 0:
        return None
    code, diff = git(folder, "diff", "-U0", "--no-color", "--no-ext-diff", base, "--", os.path.abspath(path))
    if code != 0:
        return None
    lines = set()
    for row in diff.splitlines():
        hunk = HUNK_RE.match(row)
        if hunk:
            start, count = int(hunk.group(1)), int(hunk.group(2) or "1")
            lines.update(range(start, start + count))
    return lines


def changed_files(cwd, base="HEAD"):
    """Changed and untracked .cs files of the repository holding cwd, as absolute paths."""
    code, top = git(cwd, "rev-parse", "--show-toplevel")
    if code != 0:
        return []
    top = top.strip()
    _, tracked = git(top, "diff", "--name-only", "--diff-filter=AMR", base)
    _, untracked = git(top, "ls-files", "--others", "--exclude-standard")
    names = [n for n in (tracked.splitlines() + untracked.splitlines()) if n.endswith(".cs")]
    return sorted({os.path.join(top, n) for n in names if os.path.isfile(os.path.join(top, n))})


def _line_checks(clean_lines):
    for number, line in enumerate(clean_lines, 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if VAR_RE.search(line):
            yield number, "EXPLICIT", "`var` — declare the type explicitly"
        if SERVICE_LOCATOR_RE.search(line):
            yield number, "DI", "ServiceLocator.Instance — use constructor injection or LazyService<T>"
        if DEBUG_LOG_RE.search(line):
            yield number, "LOG", "Debug.Log* — log through the project Logger wrapper"
        if stripped.endswith("{") and stripped != "{" and not INITIALISER_RE.search(stripped):
            yield number, "ALLMAN", "`{` on the same line — put the brace on its own line"


def _declaration_checks(types):
    for decl in types:
        if decl.access is None and decl.kind != "namespace":
            yield decl.line, "ACCESS", "%s %s has no access modifier" % (decl.kind, decl.name)
        if decl.kind in ("interface", "enum"):
            continue
        for member in decl.members:
            signature = member.signature or ""
            partial = re.search(r"\bpartial\b", signature)
            static_ctor = member.kind == "ctor" and member.is_static
            if member.access is None and not partial and not static_ctor:
                yield member.line, "ACCESS", "%s %s has no access modifier" % (member.kind, member.name)
            if member.kind == "field" and member.access == "public" and not re.search(r"\bconst\b", signature):
                yield member.line, "FIELD", "public field %s — wrap it in a property" % member.name
            head = signature.split("(", 1)[0]
            if (member.kind == "method" and member.is_async and re.search(r"\bvoid\b", head)
                    and not member.is_override and not EVENT_HANDLER_RE.search(signature)
                    and not HANDLER_NAME_RE.match(member.name)):
                yield member.line, "ASYNC", ("async void %s — only for event handlers and bridging overrides "
                                             "(with try/catch); return Task" % member.name)


def lint_text(path, text, lines=None):
    """[(line, tag, message)] for the text, limited to `lines` (a set) unless it is None."""
    head = "\n".join(text.split("\n")[:20])
    if any(marker in head for marker in GENERATED_MARKERS):
        return []
    clean_lines = blank_literals(text).split("\n")
    found = list(_line_checks(clean_lines))
    try:
        found += list(_declaration_checks(SourceParser().parse(path, text)))
    except Exception:   # a parser miss must not hide the line checks
        pass
    unique = sorted(set(item for item in found if lines is None or item[0] in lines))
    return unique


def lint_file(path, base="HEAD", all_lines=False):
    with open(path, encoding="utf-8-sig", errors="replace") as handle:
        text = handle.read()
    return lint_text(path, text, None if all_lines else changed_lines(path, base))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", help=".cs files (default: changed .cs files of the cwd's repo)")
    parser.add_argument("--base", default="HEAD", help="git ref the changed lines are taken against")
    parser.add_argument("--all-lines", action="store_true", help="lint every line, not only changed ones")
    args = parser.parse_args()

    files = [f for f in args.files if f.endswith(".cs")] if args.files else changed_files(os.getcwd(), args.base)
    if not files:
        print("No .cs files to lint.")
        return 0
    total = 0
    for path in files:
        if not os.path.isfile(path):
            print("%s: not found" % path, file=sys.stderr)
            continue
        for line, tag, message in lint_file(path, args.base, args.all_lines):
            print("%s:%d: [%s] %s" % (os.path.relpath(path), line, tag, message))
            total += 1
    if total:
        print("%d violation(s) in %d file(s)." % (total, len(files)))
        return 1
    print("Clean: %d file(s)." % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main())
