def tags(text, lines=None):
    return [(line, tag) for line, tag, _ in cslint.lint_text("X.cs", text, lines)]


class LintTextTests(unittest.TestCase):
    def test_clean_code_is_silent(self):
        self.assertEqual(tags(CLEAN), [])

    def test_each_tag_fires_on_its_line(self):
        found = tags(DIRTY)
        expected = [(3, "ACCESS"), (3, "ALLMAN"), (4, "FIELD"), (5, "ACCESS"), (6, "ACCESS"),
                    (8, "EXPLICIT"), (9, "EXPLICIT"), (11, "DI"), (12, "LOG"), (13, "LOG"), (17, "ASYNC")]
        self.assertEqual(found, expected)

    def test_line_filter_limits_findings(self):
        self.assertEqual(tags(DIRTY, {8, 12}), [(8, "EXPLICIT"), (12, "LOG")])

    def test_generated_files_are_skipped(self):
        self.assertEqual(tags("// <auto-generated>\n" + DIRTY), [])

    def test_allman_control_statements(self):
        text = "public class A\n{\n    public void M()\n    {\n        if (x) {\n        }\n        else {\n        }\n    }\n}\n"
        self.assertEqual(tags(text), [(5, "ALLMAN"), (7, "ALLMAN")])


class ChangedLinesTests(unittest.TestCase):
    def setUp(self):
        self.repo = tempfile.mkdtemp(prefix="cslint-")
        for args in (["init", "-q"], ["config", "user.email", "t@t"], ["config", "user.name", "t"]):
            subprocess.run(["git", "-C", self.repo] + args, check=True)
        self.path = os.path.join(self.repo, "A.cs")
        with open(self.path, "w") as handle:
            handle.write("public class A\n{\n    private void M()\n    {\n        var old = 1;\n    }\n}\n")

    def tearDown(self):
        shutil.rmtree(self.repo, ignore_errors=True)

    def test_untracked_file_lints_every_line(self):
        self.assertIsNone(cslint.changed_lines(self.path))
        self.assertEqual([(l, t) for l, t, _ in cslint.lint_file(self.path)], [(5, "EXPLICIT")])

    def test_only_changed_lines_of_a_tracked_file(self):
        subprocess.run(["git", "-C", self.repo, "add", "A.cs"], check=True)
        subprocess.run(["git", "-C", self.repo, "commit", "-qm", "base"], check=True)
        with open(self.path) as handle:
            text = handle.read()
        with open(self.path, "w") as handle:
            handle.write(text.replace("        var old = 1;\n", "        var old = 1;\n        var fresh = 2;\n"))
        self.assertEqual(cslint.changed_lines(self.path), {6})
        self.assertEqual([(l, t) for l, t, _ in cslint.lint_file(self.path)], [(6, "EXPLICIT")])
        self.assertEqual(len(cslint.lint_file(self.path, all_lines=True)), 2)
        self.assertEqual([os.path.realpath(p) for p in cslint.changed_files(self.repo)],
                         [os.path.realpath(self.path)])


